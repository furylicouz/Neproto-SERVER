export function resolveAppLocale(acceptLanguage: string | null | undefined): AppLocale {
  const languageTags = (acceptLanguage ?? "")
    .split(",")
    .map((entry) => entry.trim().split(";", 1)[0]?.toLowerCase())
    .filter(Boolean);

  return languageTags.some((tag) => tag === "ru" || tag?.startsWith("ru-")) ? "ru" : "en";
}

export function localeTag(locale: AppLocale) {
  return locale === "ru" ? "ru-RU" : "en-US";
}
